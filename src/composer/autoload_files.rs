//! The autoload maps Composer generates under `vendor/composer/`
//! (`autoload_classmap.php`, `autoload_files.php`,
//! `autoload_namespaces.php`), Composer's own bootstrap classes, and the
//! files an autoloaded file pulls in with `require_once` or from a phar.

use std::collections::{HashMap, HashSet};
use std::fs;
use std::path::{Path, PathBuf};

/// Unescape a PHP single-quoted string body.
///
/// In a single-quoted PHP string only two escape sequences are special:
/// `\\` produces a literal backslash and `\'` produces a literal quote.
/// Any other backslash is literal. A single left-to-right pass is the
/// only correct way to handle these (sequential `replace` calls are
/// order-dependent and mis-handle adjacent escapes).
fn unescape_php_single_quoted(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut chars = s.chars();
    while let Some(c) = chars.next() {
        if c == '\\' {
            match chars.next() {
                Some('\\') => out.push('\\'),
                Some('\'') => out.push('\''),
                Some(other) => {
                    out.push('\\');
                    out.push(other);
                }
                None => out.push('\\'),
            }
        } else {
            out.push(c);
        }
    }
    out
}

/// Parse `<vendor>/composer/autoload_classmap.php` and return a mapping
/// from fully-qualified class name to file path (relative to the workspace
/// root).
///
/// This file is generated by `composer install` / `composer dump-autoload`
/// and maps class names directly to their defining files.  When the user
/// runs `composer install -o` (optimised autoloader), Composer converts
/// all PSR-0 and PSR-4 mappings into a classmap, giving us complete
/// coverage of every loadable class.
///
/// The file contains lines like:
/// ```text
///     'AWS\\CRT\\Auth\\AwsCredentials' => $vendorDir . '/aws/aws-crt-php/src/AWS/CRT/Auth/AwsCredentials.php',
///     'App\\Models\\User' => $baseDir . '/app/Models/User.php',
/// ```
///
/// `$vendorDir` is resolved relative to the workspace root using the
/// configured vendor directory.  `$baseDir` is the workspace root itself.
///
/// Returns an empty `HashMap` if the file does not exist or cannot be
/// parsed.
pub fn parse_autoload_classmap(
    workspace_root: &Path,
    vendor_dir: &str,
) -> HashMap<String, PathBuf> {
    let autoload_path = workspace_root
        .join(vendor_dir)
        .join("composer")
        .join("autoload_classmap.php");

    let Some(content) = super::read_composer_file(&autoload_path) else {
        return HashMap::new();
    };

    let mut classmap = HashMap::new();

    for line in content.lines() {
        let trimmed = line.trim();

        // Match lines of the form:
        //   'Fully\\Qualified\\ClassName' => $vendorDir . '/path/to/File.php',
        //   'Fully\\Qualified\\ClassName' => $baseDir . '/path/to/File.php',
        if let Some(rest) = trimmed.strip_prefix('\'')
            && let Some(arrow_pos) = rest.find("' => ")
        {
            let class_name = unescape_php_single_quoted(&rest[..arrow_pos]);

            let rhs = rest[arrow_pos + "' => ".len()..]
                .trim()
                .trim_end_matches(',');

            if let Some(relative_path) = resolve_autoload_path_entry(rhs, vendor_dir) {
                classmap.insert(class_name, workspace_root.join(&relative_path));
            }
        }
    }

    classmap
}

/// Resolve a single path entry from `autoload_psr4.php`.
///
/// Handles `$vendorDir . '/path'` and `$baseDir . '/path'`.
fn resolve_autoload_path_entry(entry: &str, vendor_dir: &str) -> Option<String> {
    let entry = entry.trim();

    if let Some(rest) = entry.strip_prefix("$vendorDir . '") {
        // $vendorDir . '/org/pkg/src'
        let path = rest.strip_suffix('\'')?;
        let path = path.strip_prefix('/').unwrap_or(path);
        Some(format!("{}/{}", vendor_dir, path))
    } else if let Some(rest) = entry.strip_prefix("$baseDir . '") {
        // $baseDir . '/lib'
        let path = rest.strip_suffix('\'')?;
        let path = path.strip_prefix('/').unwrap_or(path);
        Some(path.to_string())
    } else {
        None
    }
}

/// Parse `<vendor>/composer/autoload_files.php` and return the resolved
/// file paths.
///
/// This file is generated by `composer install` / `composer dump-autoload`
/// and lists files that should be eagerly loaded — typically containing
/// global function definitions, `define()` calls, and similar bootstrap
/// code.
///
/// The file contains lines like:
/// ```text
///     'hash' => $vendorDir . '/org/pkg/src/functions.php',
///     'hash' => $baseDir . '/app/Http/helpers.php',
/// ```
///
/// `$vendorDir` is resolved relative to the workspace root using the
/// configured vendor directory.  `$baseDir` is the workspace root itself.
///
/// Returns an empty `Vec` if the file does not exist or cannot be parsed.
pub fn parse_autoload_files(workspace_root: &Path, vendor_dir: &str) -> Vec<PathBuf> {
    let autoload_path = workspace_root
        .join(vendor_dir)
        .join("composer")
        .join("autoload_files.php");

    let Some(content) = super::read_composer_file(&autoload_path) else {
        return Vec::new();
    };

    let mut files = Vec::new();

    for line in content.lines() {
        let trimmed = line.trim();

        // Match lines of the form:  'hash' => $vendorDir . '/path/to/file.php',
        //                       or: 'hash' => $baseDir . '/path/to/file.php',
        // We look for `=> $vendorDir` or `=> $baseDir` after the hash key.
        if let Some(arrow_pos) = trimmed.find("=> ") {
            let rhs = trimmed[arrow_pos + 3..].trim().trim_end_matches(',');

            if let Some(base_path) = resolve_autoload_path_entry(rhs, vendor_dir) {
                let full_path = workspace_root.join(&base_path);
                if full_path.is_file() {
                    files.push(full_path);
                }
            }
        }
    }

    files
}

/// Discover global-helper sibling files that frameworks load through their
/// own bootstrap rather than Composer's `files` autoload.
///
/// Some frameworks split their global function aliases into a dedicated
/// file that sits *beside* an autoloaded `functions.php` but is itself
/// pulled in by the application bootstrap, not by Composer. CakePHP is the
/// canonical case: `vendor/cakephp/cakephp/src/Core/functions.php` is in
/// `autoload_files.php`, but the global aliases (`__`, `h`, `env`, `pr`,
/// ...) live in the sibling `Core/functions_global.php`, which the app
/// loads via `require CAKE . 'functions.php'` in `config/bootstrap.php`.
/// Because that sibling never appears in `autoload_files.php`, its global
/// functions are otherwise invisible to the indexer and every `__()` call
/// resolves to "unknown function".
///
/// For each file already listed in `autoload_files.php`, this returns any
/// sibling in the same directory whose name ends in `_global.php`, so the
/// caller can scan it alongside the real autoload files. The lookup is
/// anchored to existing autoload entries (one `read_dir` per unique
/// directory) rather than a blind walk of `vendor/`, keeping it cheap.
pub fn discover_global_sibling_files(autoload_files: &[PathBuf]) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut scanned_dirs = HashSet::new();
    let mut seen_files = HashSet::new();

    for file in autoload_files {
        let Some(dir) = file.parent() else {
            continue;
        };
        if !scanned_dirs.insert(dir.to_path_buf()) {
            continue;
        }
        let Ok(entries) = fs::read_dir(dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
                continue;
            };
            if name.ends_with("_global.php") && path.is_file() && seen_files.insert(path.clone()) {
                out.push(path);
            }
        }
    }

    out
}

/// Extract file paths from `require_once` statements in PHP source content.
///
/// Handles the statement form, the function-like form, and the common
/// `__DIR__ . '...'` concatenation (used by e.g. thecodingmachine/safe
/// to dispatch to per-PHP-version function definitions):
/// ```text
///     require_once 'Trustly/exceptions.php';
///     require_once('Trustly/Data/data.php');
///     require_once __DIR__ . '/8.1/url.php';
/// ```
///
/// Other dynamic expressions (variables, multi-part concatenations)
/// are silently skipped.
///
/// Returns path strings relative to the file's directory (a leading
/// `__DIR__ . '/'` is stripped).  The caller is responsible for
/// resolving them against that directory.
pub fn extract_require_once_paths(content: &str) -> Vec<String> {
    let mut paths = Vec::new();

    for line in content.lines() {
        let trimmed = line.trim();

        // Quick reject: line must start with `require_once`.
        // (We don't support `require_once` buried in complex expressions.)
        if !trimmed.starts_with("require_once") {
            continue;
        }

        let rest = trimmed["require_once".len()..].trim_start();

        // Strip optional parentheses: `require_once('...')` → `'...'`
        // Also handles `require_once '...'` without parens.
        let rest = if let Some(inner) = rest.strip_prefix('(') {
            if let Some(end) = inner.rfind(')') {
                inner[..end].trim()
            } else {
                continue;
            }
        } else {
            rest
        };

        let rest = rest.trim_end_matches(';').trim();

        // `__DIR__ . '/x.php'` resolves the same as a bare relative
        // path, since the caller joins against the file's directory.
        let (rest, from_dir_const) = match rest.strip_prefix("__DIR__") {
            Some(after) => match after.trim_start().strip_prefix('.') {
                Some(after_dot) => (after_dot.trim_start(), true),
                None => continue,
            },
            None => (rest, false),
        };

        // Extract string literal — single or double quoted
        let path = if (rest.starts_with('\'') && rest.ends_with('\''))
            || (rest.starts_with('"') && rest.ends_with('"'))
        {
            &rest[1..rest.len() - 1]
        } else {
            // Not a simple string literal — skip
            continue;
        };

        // Strip the leading `/` left over from `__DIR__ . '/x.php'` so
        // the path stays relative (`Path::join` would otherwise treat
        // it as absolute and discard the base directory).
        let path = if from_dir_const {
            path.trim_start_matches('/')
        } else {
            path
        };

        if !path.is_empty() {
            paths.push(path.to_string());
        }
    }

    paths
}

/// Parse `<vendor>/composer/autoload_namespaces.php` (PSR-0 map) and
/// scan the listed directories for PHP classes.
///
/// PSR-0 is a legacy autoloading standard where underscores in class
/// names map to directory separators.  For example, the prefix
/// `HTMLPurifier` with base path `library/` means that the class
/// `HTMLPurifier_Config` lives at `library/HTMLPurifier/Config.php`.
///
/// Composer generates `autoload_namespaces.php` for packages that
/// declare `autoload.psr-0` in their `composer.json`.  The file
/// contains lines like:
///
/// ```text
///     'HTMLPurifier' => array($vendorDir . '/ezyang/htmlpurifier/library'),
/// ```
///
/// Rather than implementing PSR-0 name-to-path resolution (which would
/// require handling underscore splitting, prefix directories, and
/// fallback rules), we simply scan each listed directory with the
/// byte-level class scanner and return a classmap.  This gives us the
/// same result as `composer install -o` for PSR-0 packages without
/// requiring the user to run the optimised dump.
///
/// Returns an empty `HashMap` if the file does not exist or has no
/// entries.
pub fn parse_autoload_namespaces(
    workspace_root: &Path,
    vendor_dir: &str,
) -> HashMap<String, PathBuf> {
    let autoload_path = workspace_root
        .join(vendor_dir)
        .join("composer")
        .join("autoload_namespaces.php");

    let Some(content) = super::read_composer_file(&autoload_path) else {
        return HashMap::new();
    };

    // Collect all base directories listed in the PSR-0 map.
    // Each line looks like:
    //   'Prefix' => array($vendorDir . '/org/pkg/src'),
    //   'Prefix' => array($vendorDir . '/org/pkg/src', $baseDir . '/lib'),
    let mut base_dirs: Vec<PathBuf> = Vec::new();

    for line in content.lines() {
        let trimmed = line.trim();

        // Skip lines that don't look like array entries.
        if !trimmed.contains("=>") {
            continue;
        }

        let rhs = if let Some(pos) = trimmed.find("=> array(") {
            &trimmed[pos + "=> array(".len()..]
        } else if let Some(pos) = trimmed.find("=> [") {
            &trimmed[pos + "=> [".len()..]
        } else {
            continue;
        };

        let rhs =
            rhs.trim_end_matches(|c: char| c == ')' || c == ']' || c == ',' || c.is_whitespace());

        // Split by comma to handle multiple paths per prefix.
        for segment in rhs.split(',') {
            let segment = segment.trim();
            if let Some(relative_path) = resolve_autoload_path_entry(segment, vendor_dir) {
                let full_path = workspace_root.join(&relative_path);
                if full_path.is_dir() {
                    base_dirs.push(full_path);
                }
            }
        }
    }

    // Scan each base directory for PHP class files.
    let mut classmap = HashMap::new();

    for base_dir in &base_dirs {
        scan_directory_for_classes(base_dir, &mut classmap);
    }

    classmap
}

/// Scan `<vendor>/composer/` for the classes Composer's own bootstrap
/// defines, and return them as a classmap.
///
/// `Composer\Autoload\ClassLoader` and `Composer\InstalledVersions` are
/// present in every Composer install, but no autoload map lists them:
/// `vendor/composer/autoload_real.php` pulls them in with a hand-written
/// `require` before any autoloader is registered, and the directory is not
/// a package, so nothing else indexes it either.  Code that introspects
/// its own autoloader (`ClassLoader::getPrefixesPsr4()`,
/// `InstalledVersions::getRootPackage()`) names them directly, so they
/// have to be indexed for that code to resolve.
///
/// The files are scanned rather than hardcoded to a name, so a Composer
/// release that adds or renames a bootstrap class needs no change here.
/// Files that only run code (`autoload_real.php`, `platform_check.php`)
/// declare no class and contribute nothing.
///
/// Returns an empty `HashMap` when the directory does not exist.
pub fn scan_composer_bootstrap_classes(
    workspace_root: &Path,
    vendor_dir: &str,
) -> HashMap<String, PathBuf> {
    let composer_dir = workspace_root.join(vendor_dir).join("composer");
    let entries = match fs::read_dir(&composer_dir) {
        Ok(e) => e,
        Err(_) => return HashMap::new(),
    };

    let mut classmap = HashMap::new();
    for entry in entries.flatten() {
        let path = entry.path();
        // Only the directory's own files: `vendor/composer/` also holds
        // the installed-package metadata and, for a path repository, the
        // symlinks into it.
        if !path.is_file() || path.extension().is_none_or(|ext| ext != "php") {
            continue;
        }
        // The generated autoload maps are data, not declarations, and are
        // parsed by their own dedicated readers.
        if path
            .file_name()
            .and_then(|n| n.to_str())
            .is_some_and(|n| n.starts_with("autoload_"))
        {
            continue;
        }
        if let Ok(content) = fs::read(&path) {
            for fqn in crate::classmap_scanner::find_classes(&content) {
                classmap.entry(fqn).or_insert_with(|| path.clone());
            }
        }
    }

    classmap
}

/// Recursively scan a directory for PHP files and extract class names
/// using the lightweight byte-level scanner.
fn scan_directory_for_classes(dir: &Path, classmap: &mut HashMap<String, PathBuf>) {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };

    for entry in entries.flatten() {
        let path = entry.path();
        // Recurse only into real directories: following a link back up the
        // tree would re-enter it until the kernel's symlink limit stops the
        // walk.  A linked file is still read, through the link.
        let Ok(file_type) = entry.file_type() else {
            continue;
        };
        if file_type.is_dir() {
            scan_directory_for_classes(&path, classmap);
        } else if path.extension().is_some_and(|ext| ext == "php")
            && let Ok(content) = fs::read(&path)
        {
            let classes = crate::classmap_scanner::find_classes(&content);
            for fqn in classes {
                classmap.entry(fqn).or_insert_with(|| path.clone());
            }
        }
    }
}

/// Detect `.phar` archive references in a PHP bootstrap file.
///
/// Scans the file content for patterns like:
///
/// ```text
/// require 'phar://' . __DIR__ . '/phpstan.phar/vendor/autoload.php';
/// $filepath = 'phar://' . __DIR__ . '/phpstan.phar/src/' . $filename . '.php';
/// ```
///
/// Returns the absolute paths of all `.phar` files referenced in the
/// content, resolved relative to `file_dir` (the directory containing
/// the bootstrap file).
///
/// This is intentionally lenient: it looks for any `__DIR__` + string
/// concatenation that mentions a `.phar` file, regardless of the
/// surrounding PHP structure.  False positives are harmless (the phar
/// parser will reject non-phar files), and false negatives are
/// acceptable (users can always extract the phar manually).
pub fn detect_phar_references(content: &str, file_dir: &Path) -> Vec<PathBuf> {
    let mut phars = Vec::new();
    let mut seen = std::collections::HashSet::new();

    for line in content.lines() {
        // Look for lines containing both `__DIR__` and `.phar`.
        if !line.contains("__DIR__") || !line.contains(".phar") {
            continue;
        }

        // Extract the phar filename from string fragments like:
        //   '/phpstan.phar/vendor/autoload.php'
        //   '/phpstan.phar/src/'
        // We look for quoted strings containing `.phar` and extract
        // the path up to (and including) the `.phar` extension.
        for quote in *b"'\"" {
            let bytes = line.as_bytes();
            let mut i = 0;
            while i < bytes.len() {
                if bytes[i] == quote {
                    // Find the closing quote.
                    if let Some(end) = bytes[i + 1..].iter().position(|&b| b == quote) {
                        let fragment = &line[i + 1..i + 1 + end];
                        if let Some(phar_end) = fragment.find(".phar") {
                            // Extract the relative path: e.g. "/phpstan.phar"
                            let rel = &fragment[..phar_end + 5]; // +5 for ".phar"
                            let rel = rel.trim_start_matches('/');
                            if !rel.is_empty() {
                                let phar_path = file_dir.join(rel);
                                if phar_path.is_file() && seen.insert(phar_path.clone()) {
                                    phars.push(phar_path);
                                }
                            }
                        }
                        i += 1 + end + 1;
                    } else {
                        i += 1;
                    }
                } else {
                    i += 1;
                }
            }
        }
    }

    phars
}

#[cfg(test)]
mod tests {
    use super::*;

    // ── unescape_php_single_quoted ──────────────────────────────────

    #[test]
    fn unescape_namespace_separators() {
        // `App\\Models\\User` in the source is the FQN `App\Models\User`.
        assert_eq!(
            unescape_php_single_quoted("App\\\\Models\\\\User"),
            "App\\Models\\User"
        );
    }

    #[test]
    fn unescape_quote_and_backslash_before_quote() {
        // `\'` → `'` and a literal backslash followed by a quote
        // (`\\\'` → `\'`).
        assert_eq!(unescape_php_single_quoted("a\\'b"), "a'b");
        assert_eq!(unescape_php_single_quoted("a\\\\\\'b"), "a\\'b");
    }

    #[test]
    fn unescape_lone_backslash_is_literal() {
        // A backslash before a non-special character stays literal.
        assert_eq!(unescape_php_single_quoted("a\\nb"), "a\\nb");
    }

    // ── discover_global_sibling_files ───────────────────────────────

    #[test]
    fn discovers_global_sibling_beside_autoload_file() {
        // Mirrors CakePHP: an autoloaded `functions.php` sits next to a
        // `functions_global.php` sibling that Composer never lists.
        let dir = tempfile::tempdir().unwrap();
        let core = dir.path().join("Core");
        std::fs::create_dir_all(&core).unwrap();
        let autoloaded = core.join("functions.php");
        let sibling = core.join("functions_global.php");
        std::fs::write(
            &autoloaded,
            "<?php\nnamespace Cake\\Core;\nfunction toBool() {}",
        )
        .unwrap();
        std::fs::write(
            &sibling,
            "<?php\nif (!function_exists('__')) { function __() {} }",
        )
        .unwrap();

        let found = discover_global_sibling_files(&[autoloaded]);
        assert_eq!(found, vec![sibling]);
    }

    #[test]
    fn discovers_global_sibling_scans_each_directory_once() {
        // Two autoload entries in the same directory must not yield the
        // sibling twice.
        let dir = tempfile::tempdir().unwrap();
        let src = dir.path().join("src");
        std::fs::create_dir_all(&src).unwrap();
        let a = src.join("functions.php");
        let b = src.join("helpers.php");
        let sibling = src.join("functions_global.php");
        std::fs::write(&a, "<?php").unwrap();
        std::fs::write(&b, "<?php").unwrap();
        std::fs::write(&sibling, "<?php").unwrap();

        let found = discover_global_sibling_files(&[a, b]);
        assert_eq!(found, vec![sibling]);
    }

    #[test]
    fn discovers_global_sibling_returns_empty_without_sibling() {
        let dir = tempfile::tempdir().unwrap();
        let src = dir.path().join("src");
        std::fs::create_dir_all(&src).unwrap();
        let autoloaded = src.join("functions.php");
        std::fs::write(&autoloaded, "<?php").unwrap();

        assert!(discover_global_sibling_files(&[autoloaded]).is_empty());
    }
}

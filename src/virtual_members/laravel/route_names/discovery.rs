/// Resolve `route('name')` to the `->name('name')` declarations that register
/// it, as the route table recorded them.
///
/// Supports both explicit full-name declarations:
///   `Route::get('/create', ...)->name('admin.email.template.create')`
///
/// And group prefix notation:
///   `Route::name('admin.email.template.')->group(fn() { Route::get(...)->name('create'); })`
pub(crate) fn resolve_route_definitions(backend: &Backend, name: &str) -> Vec<Location> {
    backend.cached_routes().definitions(name)
}

/// Find-references starting from the `->name()` argument that registers a
/// route: every `route()` call naming it, plus the registration itself when
/// `include_declaration` is set.
///
/// `None` when the cursor is not on a route registration, which only a
/// routes file (the project's or one a package loads) can hold.
pub(crate) fn find_route_registration_references(
    backend: &Backend,
    uri: &str,
    content: &str,
    position: Position,
    include_declaration: bool,
) -> Option<Vec<Location>> {
    use crate::symbol_map::StringKeyKind;

    let is_route_file = uri.contains("/routes/")
        || crate::util::uri_to_path(uri).is_some_and(|path| {
            backend
                .laravel
                .provider_resources
                .read()
                .route_files
                .contains(&path)
        });
    if !is_route_file {
        return None;
    }

    let offset = crate::text_position::position_to_offset(content, position);
    let names = backend.cached_routes().names_registered_at(uri, offset);
    if names.is_empty() {
        return None;
    }

    let keys: Vec<_> = names
        .iter()
        .map(|key| crate::reference_index::ReferenceIndexKey::StringKey {
            kind: StringKeyKind::Route,
            key: key.clone(),
        })
        .collect();
    let snapshot = backend.user_file_symbol_maps_for_reference_keys(&keys);
    let mut locations: Vec<Location> = Vec::new();
    for name in &names {
        locations.extend(
            crate::virtual_members::laravel::find_laravel_string_key_references(
                backend,
                &StringKeyKind::Route,
                name,
                uri,
                &snapshot,
                include_declaration,
            ),
        );
    }
    // A file reached both on its own and under a named group registers
    // the same call under two names.
    crate::references::sort_locations_for_references(&mut locations);
    (!locations.is_empty()).then_some(locations)
}

/// Where go-to-definition lands for a route-name argument: between the quotes
/// of a plain literal, and at the start of anything else — an interpolated or
/// concatenated name has no single literal to point at.
fn name_offset(expr: &Expression<'_>, content: &str) -> usize {
    match extract_string_literal(expr, content) {
        Some((_, start, _)) => start,
        None => expr.span().start.offset as usize,
    }
}

/// A named route recovered from the project's route files.
#[derive(Debug)]
pub(crate) struct RouteEntry {
    /// Fully-qualified route name, with group name prefixes applied
    /// (e.g. `admin.users.index`).
    pub name: String,
    /// The URI the route was registered with, with group URI prefixes
    /// applied and reported the way Laravel's `Route::uri()` does: no
    /// leading slash, and `/` for the root route (e.g. `users/{user}`).
    ///
    /// Empty when the URI is not statically recoverable — a variable URI,
    /// or a name generated by `Route::resource()` rather than written out.
    pub uri: String,
    /// Whether the route was registered by an installed package rather
    /// than by the project itself.  A project that registers no routes of
    /// its own still sees every vendor package's routes, so consumers that
    /// need to know "does this project have a route table at all?" have to
    /// look past them.
    pub from_vendor: bool,
    /// Where the route is registered.  Registering one name twice is a
    /// mistake Laravel lets through, and every registration is somewhere the
    /// name could have come from, so a repeated name keeps them all.
    pub declarations: Vec<RouteDeclaration>,
}

/// Where a route name is registered.
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct RouteDeclaration {
    /// The file the registration is written in.
    pub file: Arc<Uri>,
    /// Where go-to-definition lands: between the quotes of a plain literal
    /// name, and at the start of anything else.
    pub position: Position,
    /// The byte range of the `->name()` argument that spells the name, when
    /// the route has one.  A name a registrar prefix, `Route::resource()` or
    /// a Folio page generates has no argument of its own to stand on.
    pub name_arg: Option<(u32, u32)>,
}

/// The result of scanning the project's route files.
#[derive(Debug)]
pub(crate) struct RouteDiscovery {
    /// Every named route that was statically resolved.
    pub routes: Vec<RouteEntry>,
    /// The name of every route in `routes`, sorted, shared so that a
    /// diagnostic pass or a completion reads the list rather than copying
    /// it.
    pub names: std::sync::Arc<[String]>,
    /// Name prefixes of groups whose `->name()` argument was not a string
    /// literal (e.g. `Route::name($panelId . '.')` inside Filament).  Routes
    /// starting with one of these prefixes cannot be judged: the full set of
    /// names under the prefix is unknowable through static analysis.
    pub open_prefixes: Vec<String>,
    /// Route names registered under a group whose name could not be
    /// statically recovered, recorded whole rather than as a prefix (e.g. a
    /// bare `Route::name($panelId)->group(…)` with no enclosing literal group
    /// spells out no known leading text at all, so no prefix can be
    /// recorded).  A `route()` call that *ends* with one of these cannot be
    /// judged: the unknown run of characters the group's name contributes
    /// could be anything, so only the part written out after it is known.
    pub open_suffixes: Vec<String>,
    /// Every file the scan read, canonically and sorted: an edit to any of
    /// them can change the routes.
    pub sources: Vec<PathBuf>,
}

impl RouteDiscovery {
    /// Where the routes `pattern` names are registered, each place once.
    pub(crate) fn definitions(&self, pattern: &str) -> Vec<Location> {
        let matching: &[RouteEntry] = if pattern.contains('*') {
            &self.routes
        } else {
            match self
                .routes
                .binary_search_by(|route| route.name.as_str().cmp(pattern))
            {
                Ok(index) => std::slice::from_ref(&self.routes[index]),
                Err(_) => &[],
            }
        };
        let mut locations: Vec<Location> = Vec::new();
        for route in matching {
            if !route_name_matches(pattern, &route.name) {
                continue;
            }
            for declaration in &route.declarations {
                let location = crate::definition::point_location(
                    (*declaration.file).clone(),
                    declaration.position,
                );
                if !locations.contains(&location) {
                    locations.push(location);
                }
            }
        }
        locations
    }

    /// The names of the routes whose `->name()` argument in `uri` covers byte
    /// `offset`.
    ///
    /// A file loaded under a named group registers its routes with the
    /// group's prefix, and one that is also a route file of its own
    /// registers them under both names.
    pub(crate) fn names_registered_at(&self, uri: &str, offset: u32) -> Vec<String> {
        self.routes
            .iter()
            .filter(|route| {
                route.declarations.iter().any(|declaration| {
                    declaration
                        .name_arg
                        .is_some_and(|(start, end)| (start..=end).contains(&offset))
                        && declaration.file.as_str() == uri
                })
            })
            .map(|route| route.name.clone())
            .collect()
    }

    /// Whether the scan read the file `uri`, so that an edit to it can change
    /// the routes.
    pub(crate) fn reads(&self, uri: &str) -> bool {
        let Some(path) = crate::util::uri_to_path(uri) else {
            return false;
        };
        if self.sources.binary_search(&path).is_ok() {
            return true;
        }
        // The sources are spelled canonically.  Resolving the path costs a
        // filesystem call, so it is only worth it for a file that has the
        // name of one of them.
        path.file_name().is_some_and(|name| {
            self.sources
                .iter()
                .any(|source| source.file_name() == Some(name))
        }) && self
            .sources
            .binary_search(&crate::util::canonical_path_for_comparison(&path))
            .is_ok()
    }
}

/// The name and URI prefixes a route inherits from the groups enclosing it,
/// and the receivers the router is reachable through at that point.
#[derive(Clone, Copy)]
struct GroupPrefix<'a> {
    /// Accumulated route-name prefix (`->name('admin.')`, `['as' => …]`).
    name: &'a str,
    /// Accumulated URI prefix (`->prefix('admin')`, `['prefix' => …]`).
    uri: &'a str,
    /// Whether this group or an enclosing one has a name that could not be
    /// statically recovered.  Once set, every route name registered beneath
    /// it is also recorded in [`RouteDiscovery::open_suffixes`], since the
    /// literal name alone (missing whatever the unknown group name
    /// contributes ahead of it) is not a route that necessarily exists.
    unknowable: bool,
    /// The variable (without its `$`) holding the router: `router` in a
    /// routes file, which Laravel's `RouteFileRegistrar` requires with
    /// `$router` in scope, and the first parameter of a group closure, which
    /// `Router::group()` calls with the router.
    router_var: Option<&'a str>,
    /// Whether `$this` is the router, as it is inside a router macro body.
    this_is_router: bool,
}

impl GroupPrefix<'_> {
    /// The scope a route source starts in, before any group opens.
    fn top_level() -> Self {
        GroupPrefix {
            name: "",
            uri: "",
            unknowable: false,
            router_var: Some("router"),
            this_is_router: false,
        }
    }

    /// Whether the call chain `expr` starts at the router, so that a
    /// `->name()` or registration verb along it is a route rather than some
    /// other builder's method (`$query->name('x')->get()`).
    ///
    /// The root has to be the `Route` facade, the router variable in scope,
    /// or `$this` inside a router macro.
    fn chain_reaches_router(&self, mut expr: &Expression<'_>, content: &str) -> bool {
        loop {
            match expr {
                Expression::Call(Call::Method(mc)) => expr = mc.object,
                Expression::Parenthesized(p) => expr = p.expression,
                Expression::Call(Call::StaticMethod(sc)) => {
                    return is_facade(sc.class, content, "Route");
                }
                Expression::Variable(Variable::Direct(variable)) => {
                    let name = bytes_to_str(variable.name).trim_start_matches('$');
                    return (self.this_is_router && name == "this")
                        || self.router_var == Some(name);
                }
                _ => return false,
            }
        }
    }
}

/// What a walk of the route sources collects.
#[derive(Default)]
pub(super) struct RouteCollector {
    pub(super) routes: Vec<RouteEntry>,
    /// The name prefixes of groups whose own name is not statically known.
    pub(super) open_prefixes: Vec<String>,
    /// Route names registered under such a group, recorded whole.
    pub(super) open_suffixes: Vec<String>,
    /// The files the walk read, canonically.
    sources: Vec<PathBuf>,
}

impl RouteCollector {
    /// The route table: one entry per name, sorted.
    pub(super) fn into_discovery(self) -> RouteDiscovery {
        let RouteCollector {
            mut routes,
            mut open_prefixes,
            mut open_suffixes,
            mut sources,
        } = self;
        // Sorting the project's own registrations ahead of a package's, and
        // known URIs ahead of unknown ones, then deduping to one entry per
        // name, means a name registered both with a literal URI and by
        // `Route::resource()` keeps the URI it has.  The entry kept for a name
        // takes over where the others were registered.
        routes.sort_by(|a, b| {
            a.name
                .cmp(&b.name)
                .then_with(|| a.from_vendor.cmp(&b.from_vendor))
                .then_with(|| a.uri.is_empty().cmp(&b.uri.is_empty()))
                .then_with(|| a.uri.cmp(&b.uri))
        });
        routes.dedup_by(|later, kept| {
            if later.name != kept.name {
                return false;
            }
            for declaration in later.declarations.drain(..) {
                if !kept.declarations.contains(&declaration) {
                    kept.declarations.push(declaration);
                }
            }
            true
        });
        open_prefixes.sort();
        open_prefixes.dedup();
        open_suffixes.sort();
        open_suffixes.dedup();
        sources.sort();
        sources.dedup();
        // `routes` is sorted by name and deduplicated, so the names come out
        // sorted too.
        let names: std::sync::Arc<[String]> =
            routes.iter().map(|route| route.name.clone()).collect();
        RouteDiscovery {
            routes,
            names,
            open_prefixes,
            open_suffixes,
            sources,
        }
    }
}

/// Registration methods whose first argument is the route URI.
const URI_FIRST_ARG_METHODS: &[&[u8]] = &[
    b"get",
    b"post",
    b"put",
    b"patch",
    b"delete",
    b"options",
    b"any",
    b"view",
    b"redirect",
    b"permanentredirect",
];

/// Recover the URI a route was registered with from its call chain.
///
/// The walk starts at the receiver of `->name()` and descends through the
/// chain links until it reaches the registration call, so modifiers between
/// the two are skipped:
/// `Route::middleware('auth')->get('/users/{user}', …)->name('users.show')`
/// records `/users/{user}`.  `Route::match(['get', 'post'], '/uri', …)` keeps
/// its URI in the second argument.
fn chain_uri(expr: &Expression<'_>, content: &str, scope: &Scope) -> Option<String> {
    let (method, args) = match expr {
        Expression::Call(Call::Method(mc)) => match &mc.method {
            ClassLikeMemberSelector::Identifier(ident) => (ident.value, &mc.argument_list),
            _ => return chain_uri(mc.object, content, scope),
        },
        Expression::Call(Call::StaticMethod(sc)) => match &sc.method {
            ClassLikeMemberSelector::Identifier(ident) => (ident.value, &sc.argument_list),
            _ => return None,
        },
        _ => return None,
    };

    let lower = method.to_ascii_lowercase();
    let uri_arg = if URI_FIRST_ARG_METHODS.contains(&lower.as_slice()) {
        args.arguments.iter().next()
    } else if lower == b"match" {
        args.arguments.iter().nth(1)
    } else {
        None
    };
    if let Some(arg) = uri_arg {
        return const_string(arg.value(), content, scope);
    }

    // Not a registration link — keep descending the chain.
    match expr {
        Expression::Call(Call::Method(mc)) => chain_uri(mc.object, content, scope),
        _ => None,
    }
}

/// Whether a router method registers a route (as opposed to modifying the
/// registrar or the route it returns).
fn is_registration_verb(method: &[u8]) -> bool {
    URI_FIRST_ARG_METHODS
        .iter()
        .chain([b"match".as_slice(), b"fallback".as_slice()].iter())
        .any(|verb| method.eq_ignore_ascii_case(verb))
}

/// The name a `->name()` leaf gives its route, and what is left of the chain
/// to walk once it has been read.
struct LeafRoute<'e, 'arena> {
    /// `None` when some part of the name is not a statically-known string.
    name: Option<String>,
    /// The part of the chain ahead of the registration, or the whole receiver
    /// when no registration was found.
    rest: Option<&'e Expression<'arena>>,
}

/// Read the full name of the route a `->name()` link belongs to.
///
/// `Route::name()` on a route *appends* to the name the registrar put in its
/// action, so `Route::name('admin.')->get(…)->name('dash')->name('board')` is
/// `admin.dashboard`.  The walk goes down the chain through every `->name()`
/// link and any other modifier until it reaches the registration verb; the
/// chain ahead of the verb supplies the registrar's name.  A chain with no
/// registration verb (a router macro such as `Route::inertia(…)`) keeps the
/// link's own name alone, as it always has.
fn leaf_route_name<'e, 'arena>(
    mc: &'e MethodCall<'arena>,
    content: &str,
    scope: &Scope,
) -> LeafRoute<'e, 'arena> {
    let own = mc
        .argument_list
        .arguments
        .iter()
        .next()
        .and_then(|arg| const_string(arg.value(), content, scope));
    // Name segments outermost-first, the one on `mc` included.
    let mut segments = vec![own.clone()];
    let mut cur: &'e Expression<'arena> = mc.object;
    loop {
        let (method, object) = match cur {
            Expression::Call(Call::Method(link)) => match &link.method {
                ClassLikeMemberSelector::Identifier(ident) => (ident.value, Some(link)),
                _ => {
                    cur = link.object;
                    continue;
                }
            },
            Expression::Call(Call::StaticMethod(sc)) => match &sc.method {
                ClassLikeMemberSelector::Identifier(ident) => (ident.value, None),
                _ => break,
            },
            _ => break,
        };
        if is_registration_verb(method) {
            let (registrar, rest) = match object {
                Some(link) => (chain_name_prefix(link.object, content), Some(link.object)),
                None => (String::new(), None),
            };
            let name = segments
                .iter()
                .rev()
                .try_fold(registrar, |mut name, segment| {
                    name.push_str(segment.as_deref()?);
                    Some(name)
                });
            return LeafRoute { name, rest };
        }
        let Some(link) = object else {
            break;
        };
        if method.eq_ignore_ascii_case(b"name") {
            segments.push(
                link.argument_list
                    .arguments
                    .iter()
                    .next()
                    .and_then(|arg| const_string(arg.value(), content, scope)),
            );
        }
        cur = link.object;
    }
    LeafRoute {
        name: own,
        rest: Some(mc.object),
    }
}

/// Build the recorded URI of a route from its group prefix and own URI.
fn route_uri(group_uri: &str, own_uri: Option<&str>) -> String {
    let Some(own_uri) = own_uri else {
        return String::new();
    };
    let joined = join_uri_segments(group_uri, own_uri);
    if joined.is_empty() {
        "/".to_string()
    } else {
        joined
    }
}

/// Extract the parameter names from a route URI pattern.
///
/// `users/{user}/posts/{post?}` yields `["user", "post"]`: the optional
/// marker and the scoped-binding field of `{post:slug}` are stripped, so the
/// result is exactly the keys `route()`'s parameters array accepts.
pub(crate) fn route_uri_parameters(uri: &str) -> Vec<&str> {
    let mut params = Vec::new();
    let mut rest = uri;
    while let Some(open) = rest.find('{') {
        rest = &rest[open + 1..];
        let Some(close) = rest.find('}') else {
            break;
        };
        let raw = &rest[..close];
        rest = &rest[close + 1..];
        let name = raw
            .split_once(':')
            .map_or(raw, |(name, _field)| name)
            .trim_end_matches('?');
        if !name.is_empty() {
            params.push(name);
        }
    }
    params
}

/// Collect all named routes defined in `routes/` files.
///
/// Returns a sorted, deduplicated list of fully-qualified route names with
/// the URI each was registered with.
///
/// Follows `Route::group([], __DIR__ . '/sub.php')` file includes so
/// that routes in sub-files inherit the parent group's prefixes.
pub(crate) fn enumerate_all_routes(backend: &Backend) -> RouteDiscovery {
    let mut collector = RouteCollector::default();
    let mut scanned: HashSet<PathBuf> = HashSet::new();
    let snapshot = backend.user_file_symbol_maps();
    let workspace_root = backend.workspace.workspace_root.read().clone();
    let macros = MacroScope::for_backend(backend);
    let mut subdirectory_files = Vec::new();

    for (file_uri, _) in snapshot {
        if !file_uri.contains("/routes/") {
            continue;
        }
        // A route file in a sub-directory of `routes/` is not loaded by
        // Laravel on its own: a parent file pulls it in with
        // `Route::group([], __DIR__ . '/sub.php')`, and it is scanned in that
        // context to inherit the correct name prefix.  A "sub-directory" file
        // is one where the path after the last `/routes/` segment contains
        // another `/`.
        if let Some(after) = file_uri.rsplit("/routes/").next()
            && after.contains('/')
        {
            subdirectory_files.push(file_uri);
            continue;
        }
        walk_workspace_route_file(
            backend,
            &file_uri,
            workspace_root.as_deref(),
            &macros,
            &mut collector,
            &mut scanned,
        );
    }

    // Copied out so the lock is not held across the file reads.
    let provider_route_files = backend
        .laravel
        .provider_resources
        .read()
        .route_files
        .clone();
    for route_path in &provider_route_files {
        let canonical = route_path
            .canonicalize()
            .unwrap_or_else(|_| route_path.clone());
        if !scanned.insert(canonical.clone()) {
            continue;
        }
        if let Ok(content) = std::fs::read_to_string(route_path)
            && let Some(uri) = crate::util::path_to_url(route_path)
        {
            collector.sources.push(canonical);
            let before = collector.routes.len();
            walk_route_file(
                &content,
                &uri,
                Some(route_path),
                workspace_root.as_deref(),
                &macros,
                &mut collector,
            );
            if route_path
                .components()
                .any(|part| part.as_os_str() == "vendor")
            {
                mark_from_vendor(&mut collector.routes[before..]);
            }
        }
    }

    // A sub-directory file that nothing above loads is loaded by something
    // the scan cannot follow, such as a loop over `glob()`, so it is read on
    // its own rather than dropped.
    subdirectory_files.sort();
    for file_uri in subdirectory_files {
        let loaded = crate::util::uri_to_path(&file_uri).is_some_and(|path| {
            let canonical = path.canonicalize().unwrap_or(path);
            collector.sources.contains(&canonical)
        });
        if !loaded {
            walk_workspace_route_file(
                backend,
                &file_uri,
                workspace_root.as_deref(),
                &macros,
                &mut collector,
                &mut scanned,
            );
        }
    }

    // Folio pages register no `Route::` call at all, so they are invisible
    // to everything above and are discovered by their own filesystem-based
    // scan instead.
    for (route, page) in crate::virtual_members::laravel::folio::enumerate_folio_routes(backend) {
        collector.sources.push(page.canonicalize().unwrap_or(page));
        collector.routes.push(route);
    }

    collector.into_discovery()
}

/// Walk the workspace route file `file_uri`, read through the editor's buffer
/// when it is open, as a route source of its own.
fn walk_workspace_route_file(
    backend: &Backend,
    file_uri: &str,
    workspace_root: Option<&Path>,
    macros: &MacroScope,
    collector: &mut RouteCollector,
    scanned: &mut HashSet<PathBuf>,
) {
    let Some(content) = backend.get_file_content(file_uri) else {
        return;
    };
    let Some(uri) = crate::util::parse_url(file_uri) else {
        return;
    };
    let path = crate::util::url_to_path(&uri);
    if let Some(ref p) = path {
        let canonical = p.canonicalize().unwrap_or_else(|_| p.clone());
        scanned.insert(canonical.clone());
        collector.sources.push(canonical);
    }
    let before = collector.routes.len();
    walk_route_file(
        &content,
        &uri,
        path.as_deref(),
        workspace_root,
        macros,
        collector,
    );
    if file_uri.contains("/vendor/") {
        mark_from_vendor(&mut collector.routes[before..]);
    }
}

fn mark_from_vendor(routes: &mut [RouteEntry]) {
    for route in routes {
        route.from_vendor = true;
    }
}

/// Parse a single route file and walk every `->name('...')` value into `sink`,
/// accounting for group prefixes and file includes.
pub(super) fn walk_route_file(
    content: &str,
    uri: &Uri,
    file_path: Option<&Path>,
    workspace_root: Option<&Path>,
    macros: &MacroScope,
    sink: &mut RouteCollector,
) {
    let open = RefCell::new(HashSet::new());
    if let Some(path) = file_path {
        open.borrow_mut()
            .insert(path.canonicalize().unwrap_or_else(|_| path.to_path_buf()));
    }
    let uri = Arc::new(uri.clone());
    let lines = LineIndex::new(content);
    in_parsed_route_file(content, b"input.php", |program| {
        let paths = ScanPaths::new(
            file_path.and_then(Path::parent),
            workspace_root,
            &open,
            macros,
            program,
            &uri,
            &lines,
        );

        let mut scope = Scope::default();
        for stmt in program.statements.iter() {
            walk_stmt(
                stmt,
                content,
                GroupPrefix::top_level(),
                paths,
                &mut scope,
                sink,
            );
        }
    });
}

fn walk_stmt(
    stmt: &Statement<'_>,
    content: &str,
    group: GroupPrefix<'_>,
    paths: ScanPaths<'_>,
    scope: &mut Scope,
    sink: &mut RouteCollector,
) {
    match stmt {
        Statement::Expression(e) => {
            walk_expr(e.expression, content, group, paths, scope, sink);
        }
        Statement::Return(r) => {
            if let Some(v) = r.value {
                walk_expr(v, content, group, paths, scope, sink);
            }
        }
        // A loop over a literal array registers one route per element, so the
        // body is walked once per element with the loop variables bound to it.
        Statement::Foreach(fe) => {
            for_each_iteration(fe, content, scope, &mut |scope| {
                for nested in fe.body.statements() {
                    walk_stmt(nested, content, group, paths, scope, sink);
                }
            });
            return;
        }
        _ => {}
    }
    for_each_nested_statement(stmt, &mut |nested| {
        walk_stmt(nested, content, group, paths, scope, sink);
    });
}

fn walk_expr(
    expr: &Expression<'_>,
    content: &str,
    group: GroupPrefix<'_>,
    paths: ScanPaths<'_>,
    scope: &mut Scope,
    sink: &mut RouteCollector,
) {
    // A chain that registers a resource generates its whole route set here;
    // none of the per-route handling below applies to it.
    if let Some(registration) = resource_registration(expr, content)
        && group.chain_reaches_router(expr, content)
    {
        let mut push_name = |name_expr| {
            if let Some((name, offset, _)) = resource_string_literal(name_expr, content) {
                push_resource_routes(
                    &registration,
                    name,
                    group,
                    paths.declaration(offset, None),
                    sink,
                );
            }
        };
        if registration.multiple {
            for element in resource_array_elements(registration.names) {
                if let ArrayElement::KeyValue(pair) = element {
                    push_name(pair.key);
                }
            }
        } else {
            push_name(registration.names);
        }
        // A `->group()` sharing the chain registers routes of its own, which
        // the resource shortcut must not swallow.
        if let Some(preceding) = registration.preceding {
            walk_expr(preceding, content, group, paths, scope, sink);
        }
        return;
    }

    match expr {
        Expression::Call(Call::Method(mc)) => {
            let ClassLikeMemberSelector::Identifier(ident) = &mc.method else {
                walk_expr(mc.object, content, group, paths, scope, sink);
                return;
            };
            let method = ident.value.to_ascii_lowercase();

            if method == b"group" {
                // When the chain includes a `->name()` whose argument is not
                // a string literal, the accumulated prefix is incomplete and
                // routes under it cannot be judged.  Whatever known text was
                // written out is still recorded as an open prefix, and every
                // route name registered inside the group from here on is
                // also unknowable, regardless of whether that text is empty.
                let dynamic_head = chain_dynamic_name_prefix(mc.object, content, scope);
                if let Some(head) = &dynamic_head {
                    record_open_prefix(group.name, head, sink);
                }
                let name_prefix =
                    format!("{}{}", group.name, chain_name_prefix(mc.object, content));
                let uri_prefix =
                    join_uri_segments(group.uri, &chain_uri_prefix(mc.object, content));
                let inner = GroupPrefix {
                    name: &name_prefix,
                    uri: &uri_prefix,
                    unknowable: group.unknowable || dynamic_head.is_some(),
                    ..group
                };
                for arg in mc.argument_list.arguments.iter() {
                    walk_group_body(arg.value(), content, inner, paths, scope, sink);
                }
            } else if method == b"name" {
                let leaf = leaf_route_name(mc, content, scope);
                if let Some(first_arg) = mc.argument_list.arguments.iter().next()
                    && let Some(name_val) = &leaf.name
                    && group.chain_reaches_router(mc.object, content)
                {
                    let full = format!("{}{name_val}", group.name);
                    // Only collect leaf names (non-prefix names that don't end with '.').
                    if !full.is_empty() && !full.ends_with('.') {
                        // A group ancestor left its own name unknowable, so
                        // this route's real name has an unrecoverable run of
                        // characters ahead of `full` — record it as an open
                        // suffix rather than trusting `full` as the whole
                        // name.
                        if group.unknowable {
                            sink.open_suffixes.push(full.clone());
                        }
                        // A `->prefix()` on the route's own chain
                        // (`Route::prefix('admin')->get(…)`) prefixes the URI
                        // just as an enclosing group's does.
                        let uri_prefix =
                            join_uri_segments(group.uri, &chain_uri_prefix(mc.object, content));
                        let name_arg = first_arg.value().span();
                        sink.routes.push(RouteEntry {
                            name: full,
                            uri: route_uri(
                                &uri_prefix,
                                chain_uri(mc.object, content, scope).as_deref(),
                            ),
                            from_vendor: false,
                            declarations: vec![paths.declaration(
                                name_offset(first_arg.value(), content),
                                Some((name_arg.start.offset, name_arg.end.offset)),
                            )],
                        });
                    }
                }
                if let Some(rest) = leaf.rest {
                    walk_expr(rest, content, group, paths, scope, sink);
                }
            } else if is_registration_verb(ident.value) {
                // `Route::name('users.index')->get(…)`: the registrar's name
                // becomes the route's even with no `->name()` after the verb.
                let registrar = chain_name_prefix(mc.object, content);
                let full = format!("{}{registrar}", group.name);
                if !registrar.is_empty()
                    && !full.ends_with('.')
                    && group.chain_reaches_router(mc.object, content)
                {
                    if group.unknowable {
                        sink.open_suffixes.push(full.clone());
                    }
                    let uri_prefix =
                        join_uri_segments(group.uri, &chain_uri_prefix(mc.object, content));
                    sink.routes.push(RouteEntry {
                        name: full,
                        uri: route_uri(&uri_prefix, chain_uri(expr, content, scope).as_deref()),
                        from_vendor: false,
                        declarations: vec![
                            paths.declaration(expr.span().start.offset as usize, None),
                        ],
                    });
                }
                walk_expr(mc.object, content, group, paths, scope, sink);
            } else if !walk_macro(ident.value, Some(mc.object), content, group, paths, sink) {
                walk_expr(mc.object, content, group, paths, scope, sink);
            }
        }
        Expression::Call(Call::StaticMethod(sc)) => {
            let ClassLikeMemberSelector::Identifier(ident) = &sc.method else {
                return;
            };
            let method_lower = ident.value.to_ascii_lowercase();

            if method_lower == b"group" {
                let args = || sc.argument_list.arguments.iter().map(|a| a.value());
                // `['as' => $dynamic]` is the legacy spelling of the fluent
                // `->name($dynamic)` group above and leaves the same names
                // unknowable.
                let dynamic_head = dynamic_as_prefix_from_args(args(), content, scope);
                if let Some(head) = &dynamic_head {
                    record_open_prefix(group.name, head, sink);
                }
                let name_prefix = format!(
                    "{}{}",
                    group.name,
                    extract_as_prefix_from_args(args(), content)
                );
                let uri_prefix =
                    join_uri_segments(group.uri, &extract_uri_prefix_from_args(args(), content));
                let inner = GroupPrefix {
                    name: &name_prefix,
                    uri: &uri_prefix,
                    unknowable: group.unknowable || dynamic_head.is_some(),
                    ..group
                };
                for arg in sc.argument_list.arguments.iter() {
                    walk_group_body(arg.value(), content, inner, paths, scope, sink);
                }
            } else {
                // `Auth::routes()` registers nothing itself: the facade
                // forwards to the router's `auth` macro, which `laravel/ui`
                // ships as a mixin.
                let macro_name: &[u8] =
                    if method_lower == b"routes" && is_facade(sc.class, content, "Auth") {
                        b"auth"
                    } else {
                        ident.value
                    };
                walk_macro(macro_name, None, content, group, paths, sink);
            }
        }
        // The data a route file loops over is usually built in a variable
        // first, and a registration is occasionally assigned to one too.
        Expression::Assignment(assignment) => {
            bind_assignment(assignment, content, scope);
            walk_expr(assignment.rhs, content, group, paths, scope, sink);
        }
        // A route file pulled in by `require`/`include` registers its routes
        // under whichever group encloses the include.
        Expression::Construct(construct) => {
            if let Some(file) = include_target(construct) {
                walk_included_file(file, content, group, paths, scope, sink);
            }
        }
        _ => {}
    }
}

/// Record the prefix a group whose own name is not statically known leaves
/// open: what its enclosing groups contribute, plus however much of its own
/// name was written out.
///
/// A group that leaves nothing at all known (`Route::name($prefix)` at the top
/// of a routes file) is not recorded: the empty prefix is a prefix of every
/// route name there is, so it would stop route names being judged anywhere in
/// the project rather than under the one group.
fn record_open_prefix(group_name: &str, head: &str, sink: &mut RouteCollector) {
    let prefix = format!("{group_name}{head}");
    if !prefix.is_empty() {
        sink.open_prefixes.push(prefix);
    }
}

/// Whether the subject of a static call spells the Laravel facade `facade`
/// (`Auth`, `Route`), by its short name or its full one.
fn is_facade(class: &Expression<'_>, content: &str, facade: &str) -> bool {
    let span = class.span();
    let Some(text) = content.get(span.start.offset as usize..span.end.offset as usize) else {
        return false;
    };
    let text = text.trim_start_matches('\\');
    let short = text
        .strip_prefix("Illuminate\\Support\\Facades\\")
        .unwrap_or(text);
    short.eq_ignore_ascii_case(facade)
}

/// Collect the route names a call to the router macro `method` registers.
///
/// A macro body registers on the router itself (`$this->get(…)->name(…)`), so
/// it is walked exactly as a `->group()` closure is, with the prefixes in force
/// at the call site — both the enclosing groups' and any the chain ahead of the
/// call adds, since `Route::name('admin.')->auth()` prefixes the macro's routes
/// the way it would a group's.
///
/// Returns `false` when `method` names no known router macro, so a caller
/// looking at an ordinary chain link can carry on down the chain.
fn walk_macro(
    method: &[u8],
    chain: Option<&Expression<'_>>,
    content: &str,
    group: GroupPrefix<'_>,
    paths: ScanPaths<'_>,
    sink: &mut RouteCollector,
) -> bool {
    let Some(open) = open_route_macro(paths.macros, method) else {
        return false;
    };
    let name_prefix = match chain {
        Some(chain) => format!("{}{}", group.name, chain_name_prefix(chain, content)),
        None => group.name.to_string(),
    };
    let uri_prefix = match chain {
        Some(chain) => join_uri_segments(group.uri, &chain_uri_prefix(chain, content)),
        None => group.uri.to_string(),
    };
    let inner = GroupPrefix {
        name: &name_prefix,
        uri: &uri_prefix,
        unknowable: group.unknowable,
        // The macro closure is bound to the router and sees none of the
        // caller's variables.
        router_var: None,
        this_is_router: true,
    };
    sink.sources.push(
        open.path
            .canonicalize()
            .unwrap_or_else(|_| open.path.clone()),
    );
    let lines = LineIndex::new(&open.content);
    in_parsed_route_file(&open.content, b"macro.php", |program| {
        let sub_paths = ScanPaths {
            dir: open.path.parent(),
            program,
            uri: &open.uri,
            lines: &lines,
            ..paths
        };

        // A macro closure is registered without a `use (...)` clause, so it
        // has no access to the caller's local variables; its body gets its own
        // scope.
        let mut scope = Scope::default();
        match macro_body_at(Node::Program(program), open.offset) {
            Some(MacroBody::Closure(closure)) => {
                for stmt in closure.body.statements.iter() {
                    walk_stmt(stmt, &open.content, inner, sub_paths, &mut scope, sink);
                }
            }
            Some(MacroBody::Arrow(arrow)) => {
                walk_expr(
                    arrow.expression,
                    &open.content,
                    inner,
                    sub_paths,
                    &mut scope,
                    sink,
                );
            }
            None => {}
        }
    });
    true
}

/// Record the conventional routes a `Route::resource()` registration
/// generates, deriving each URI from the resource name the way Laravel's
/// `ResourceRegistrar` does.
fn push_resource_routes(
    registration: &ResourceRegistration<'_>,
    name: &str,
    group: GroupPrefix<'_>,
    declaration: RouteDeclaration,
    sink: &mut RouteCollector,
) {
    let (path_prefix, resource) = split_resource_prefix(name);
    let segments: Vec<&str> = resource.split('.').collect();
    // `split` keeps even an empty last segment, just as Laravel's explode().
    let last = segments[segments.len() - 1];

    // Every URI prefix in scope — the enclosing groups' and the one a slash in
    // the resource name implies — is applied once here rather than per
    // generated route.  A `->prefix()` on the registration's own chain is not
    // among them: `ResourceRegistrar` never reads it.
    let uri_prefix = join_uri_segments(group.uri, path_prefix);
    let collection_uri = nested_resource_uri(&segments, &registration.parameters);
    // `->shallow()` reduces a nested resource to its last segment on the
    // routes that already identify the child by its own id — the name loses
    // the parent segments along with the URI.
    let (member_uri, member_name): (&str, &str) = if registration.shallow {
        (last, last)
    } else {
        (&collection_uri, resource)
    };
    let member_uri = if registration.kind.is_singleton() {
        Cow::Borrowed(member_uri)
    } else {
        Cow::Owned(format!(
            "{member_uri}/{{{}}}",
            resource_wildcard(last, &registration.parameters)
        ))
    };

    for suffix in filtered_resource_suffixes(registration) {
        let (name_base, uri) = match suffix {
            "create" => (resource, Cow::Owned(format!("{collection_uri}/create"))),
            // Unlike its edit/update/destroy routes, a singleton's show route
            // retains its parents even when shallow routing is requested.
            "show" if registration.kind.is_singleton() => {
                (resource, Cow::Borrowed(collection_uri.as_str()))
            }
            "show" | "update" | "destroy" => (member_name, Cow::Borrowed(member_uri.as_ref())),
            "edit" => (member_name, Cow::Owned(format!("{member_uri}/edit"))),
            // index and store.
            _ => (resource, Cow::Borrowed(collection_uri.as_str())),
        };
        // Trim only after appending the action path: an empty nested segment
        // may leave a meaningful slash immediately before its wildcard.
        let mut uri = join_uri_segments(&uri_prefix, &uri);
        if uri.is_empty() {
            uri.push('/');
        }
        let name = resource_route_name(registration, name_base, suffix, group.name);
        // As with a plain `->name()` leaf, an ancestor group whose own name
        // is unknowable means `name` is missing whatever unrecoverable text
        // that group contributes ahead of it.
        if group.unknowable {
            sink.open_suffixes.push(name.clone());
        }
        sink.routes.push(RouteEntry {
            name,
            uri,
            from_vendor: false,
            declarations: vec![declaration.clone()],
        });
    }
}

/// The name Laravel gives one generated resource route.
///
/// Mirrors `ResourceRegistrar::getResourceRouteName()`: a per-method
/// `->names([…])` / `->name($method, …)` entry is the whole name and skips the
/// `->as()` prefix, `->names('images')` replaces the resource name but keeps
/// it, and the trailing `trim` is what keeps a resource registered under an
/// empty name from producing a leading dot.  The enclosing groups' name
/// prefix is applied outside that, so it reaches even the per-method form.
fn resource_route_name(
    registration: &ResourceRegistration<'_>,
    name_base: &str,
    suffix: &str,
    group_name: &str,
) -> String {
    if let Some((_, route_name)) = registration
        .names_by_method
        .iter()
        .rev()
        .find(|(method, _)| method == suffix)
    {
        return format!("{group_name}{route_name}");
    }
    let base = registration.names_all.as_deref().unwrap_or(name_base);
    let prefix = match registration.name_prefix.as_deref() {
        Some(prefix) => format!("{prefix}."),
        None => String::new(),
    };
    let name = format!("{prefix}{base}.{suffix}");
    format!("{group_name}{}", name.trim_matches('.'))
}

/// Walk the argument that was passed to `->group()`.
///
/// Handles closures, arrow functions, and the file-path form
/// (`Route::group([], __DIR__ . '/sub.php')`), so routes defined in an
/// included sub-file are reached too.
fn walk_group_body(
    expr: &Expression<'_>,
    content: &str,
    group: GroupPrefix<'_>,
    paths: ScanPaths<'_>,
    scope: &mut Scope,
    sink: &mut RouteCollector,
) {
    match expr {
        Expression::Closure(closure) => {
            let group = match closure.parameter_list.parameters.first() {
                Some(param) => GroupPrefix {
                    router_var: Some(bytes_to_str(param.variable.name).trim_start_matches('$')),
                    ..group
                },
                None => group,
            };
            for stmt in closure.body.statements.iter() {
                walk_stmt(stmt, content, group, paths, scope, sink);
            }
        }
        Expression::ArrowFunction(af) => {
            walk_expr(af.expression, content, group, paths, scope, sink);
        }
        // `Route::group([], __DIR__ . '/sub.php')` names a file rather than a
        // callback.
        _ => walk_included_file(expr, content, group, paths, scope, sink),
    }
}

/// Walk a file another route source pulls in.
///
/// The file is walked with the group prefix in force at the include site so
/// its routes inherit the enclosing group's name (e.g. `admin.`).  Walking
/// with an empty prefix would produce unprefixed names that are incorrect,
/// which is why `walk_route_file` (which resets the prefix) is not used here.
fn walk_included_file(
    file: &Expression<'_>,
    content: &str,
    group: GroupPrefix<'_>,
    paths: ScanPaths<'_>,
    scope: &mut Scope,
    sink: &mut RouteCollector,
) {
    let Some(included) = open_included_file(file, content, paths) else {
        return;
    };
    let sub_uri = crate::util::path_to_url(&included.path)
        .map(Arc::new)
        .unwrap_or_else(|| Arc::clone(paths.uri));
    // Already canonical: the include stack holds each file by that spelling.
    sink.sources.push(included.path.clone());

    let lines = LineIndex::new(&included.content);
    in_parsed_route_file(&included.content, b"included.php", |program| {
        let sub_paths = ScanPaths {
            dir: included.path.parent(),
            program,
            uri: &sub_uri,
            lines: &lines,
            ..paths
        };

        for stmt in program.statements.iter() {
            walk_stmt(stmt, &included.content, group, sub_paths, scope, sink);
        }
    });
}
